import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
await mkdir('artifacts/segmentation', { recursive: true });
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--disable-gpu','--disable-software-rasterizer','--disable-webgpu']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error') console.log(m.text().slice(0,600));});
await page.goto('http://127.0.0.1:4173');
console.log('WebGPU usable:',await page.evaluate(async()=>Boolean(await navigator.gpu?.requestAdapter())));
await page.locator('input[type=file]').setInputFiles('piza.HEIC');
await page.getByRole('button',{name:'Auto',exact:true}).waitFor({timeout:60000});
await page.getByRole('button',{name:'Auto',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('.selection-section')||document.querySelector('.editor-hint.error'),{},{timeout:180000});
console.log(await page.locator('body').innerText());
console.log('pageerrors:',errors);
if(await page.locator('.selection-section').count()!==1||errors.length) process.exitCode=1;
await page.screenshot({path:'artifacts/segmentation/pisa-production-wasm.png'});
await browser.close();
